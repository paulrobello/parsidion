"""ENH-068 — prompt-template injection-framing gate.

Fails when any prompt template under ``skills/parsidion/templates/prompts/``
inlines untrusted content (transcript text, note bodies, vault content)
without SEC-108/SEC-115 framing: a ``SYSTEM:`` preamble declaring the block
UNTRUSTED DATA plus explicit delimiters wrapping the variable reference.
Generalizes the SEC-001 (summarize-chunk) and SEC-002 (repair-frontmatter)
fixes across the whole directory: the directory is the contract, so a new
template is covered the moment it lands. The completeness check makes an
unclassified template a gate failure, forcing a reviewer to decide — per
variable — whether it carries vault content (untrusted) or scaffolding
(trusted allowlist).

A variable carrying untrusted content must satisfy both:

1. The template body contains a ``SYSTEM:`` line declaring the inlined block
   untrusted data (case-insensitive match so SEC-108's full-caps and
   SEC-115's prose styles both pass).
2. The variable reference sits on a line of its own, wrapped in a delimiter
   pair: the preceding and following lines are both marker lines — either
   ``---BEGIN X---``-style dash markers or ``<tag>`` / ``</tag>`` XML-style
   markers.

Trusted scaffolding variables are exempt (see ``_TRUSTED``); allowlist
entries carry a justification so a reviewer can re-judge them.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

import pytest

_SCRIPTS_DIR = (
    Path(__file__).resolve().parent.parent / "skills" / "parsidion" / "scripts"
)
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

from parsidion.prompt_templates import (  # noqa: E402
    _coerce_variables,
    _parse_frontmatter,
)

#: Directory holding the prompt templates (the gate's contract surface).
PROMPTS_DIR = (
    Path(__file__).resolve().parent.parent
    / "skills"
    / "parsidion"
    / "templates"
    / "prompts"
)

# ---------------------------------------------------------------------------
# Variable classification registry.
#
# Every variable declared in every template's frontmatter must be classified
# in exactly one of the two tables below; an unclassified variable (or an
# unclassified new template) is a gate failure. Justifications are review
# anchors: change one, and the reviewer re-judges the classification.
# ---------------------------------------------------------------------------

#: Scaffolding variables that do NOT carry vault content — safe to inline
#: without framing. One justification per entry.
