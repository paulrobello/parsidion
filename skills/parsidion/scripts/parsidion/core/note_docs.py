def load_note_index_rows(vault: Path) -> list[NoteEntry] | None:
    """Read every ``note_index`` row as NoteEntry objects, ordered by path.

    Returns None when ``embeddings.db`` or the ``note_index`` table is
    absent, or when a core column is missing (a table this old cannot carry
    the docs) -- the caller's signal to fall back to the note-parse
    generation. Optional columns missing on pre-migration indexes
    (``date``, ``prompt_version``, ``incoming_stems``, ``status``) are
    selected as literal defaults, mirroring the snapshot reader.

    Path order is the docs' canonical order: it equals the sorted walk the
    parse path iterates, which is what makes the two doc generations
    byte-identical.
    """
    db_path = get_embeddings_db_path(vault)
    if not db_path.exists():
        return None
    try:
        conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    except sqlite3.OperationalError:
        return None
    try:
        table = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' and name='note_index'"
        ).fetchone()
        if table is None:
            return None
        cols = {row[1] for row in conn.execute("PRAGMA table_info(note_index)")}
        for core_col in (
            "stem",
            "path",
            "folder",
            "title",
            "summary",
            "tags",
            "mtime",
            "is_stale",
        ):
            if core_col not in cols:
                return None
        sel_date = "date" if "date" in cols else "'' AS date"
        sel_pv = (
            "prompt_version" if "prompt_version" in cols else "'' AS prompt_version"
        )
        sel_is = (
            "incoming_stems" if "incoming_stems" in cols else "'[]' AS incoming_stems"
        )
        sel_status = "status" if "status" in cols else "'live' AS status"
        raw = conn.execute(
            f"SELECT stem, path, folder, title, summary, tags, note_type, "
            f"project, confidence, mtime, related, is_stale, incoming_links, "
            f"{sel_date}, {sel_pv}, {sel_is}, {sel_status} "
            f"FROM note_index ORDER BY path"
        ).fetchall()
        # Per-FILE completeness: note_index holds one winner per stem; the
        # non-winner rows live in note_variants (path-keyed). Absence of the
        # table (pre-variants database) means no variants recorded.
        try:
            vraw = conn.execute(
                "SELECT path, stem, folder, title, summary, tags, mtime, is_stale"
                " FROM note_variants ORDER BY path"
            ).fetchall()
        except sqlite3.OperationalError:
            vraw = []
    except sqlite3.Error:
        return None
    finally:
        conn.close()

    def _entry(path, stem, folder, title, summary, tags, mtime, is_stale):
        return NoteEntry(
            stem=stem,
            path=path,
            folder=folder,
            title=title,
            summary=summary,
            tags=tags,
            note_type="",
            project="",
            confidence="",
            mtime=mtime,
            related="",
            is_stale=int(is_stale or 0),
            incoming_links=0,
        )

    rows = [
        NoteEntry(
            stem=r[0],
            path=r[1],
            folder=r[2],
            title=r[3],
            summary=r[4],
            tags=r[5],
            note_type=r[6],
            project=r[7],
            confidence=r[8],
            mtime=r[9],
            related=r[10],
            is_stale=int(r[11] or 0),
            incoming_links=int(r[12] or 0),
            date=str(r[13] or ""),
            prompt_version=str(r[14] or ""),
            incoming_stems=str(r[15] or ""),
            status=str(r[16] or "live"),
        )
        for r in raw
    ]
    rows.extend(_entry(*v) for v in vraw)
    rows.sort(key=lambda entry: entry.path)
    return rows


def render_docs_from_rows(
    rows: list[NoteEntry],
    *,
    vault: Path,
    total_notes: int,
    now: datetime,
) -> tuple[
    str,
    str,
    dict[str, list[tuple[str, str, str, list[str], bool]]],
    Counter[str],
]:
    """Generate the three vault docs from ``note_index`` rows alone.

    Derives everything CLAUDE.md / TAGS.md / MANIFEST.md render -- tag
    counter, per-folder manifest entries, recent-activity list, stale count
    -- from the rows, then emits through the same emitters the parse path
    uses, so both generations are byte-identical when the rows match a fresh
    parse (pinned by tests/test_note_docs_equivalence.py). Never parses a
    note file.

    Tag order note: the counter is built by scanning *rows* (path order)
    inserting each row's tags in sorted order -- the same insertion order a
    parse run produces since the parse path also counts ``sorted(tags)`` per
    note, which is what makes most_common() tie order agree.

    Args:
        rows: NoteEntry rows (path-ordered; e.g. from
            :func:`load_note_index_rows` or a fresh parse's db_rows).
        vault: Vault root (doctor_state.json read + manifest paths).
        total_notes: Walked note count for CLAUDE.md's "Total notes".
        now: Run timestamp; drives the recent-activity cutoff and headers.

    Returns:
        ``(claude_md, tags_md, folder_notes, tag_counter)`` -- write the
        first two directly, pass the third to :func:`build_manifests`; the
        counter backs the run's tag-count reporting.
    """
    now_str: str = now.strftime("%Y-%m-%d %H:%M")
    cutoff_ts: float = (now - timedelta(days=RECENT_DAYS)).timestamp()

    tag_counter: Counter[str] = Counter()
    folder_notes: dict[str, list[tuple[str, str, str, list[str], bool]]] = {}
    stale_count: int = 0
    recent_notes: list[tuple[float, Path, str, str]] = []
    for row in rows:
        tags_list: list[str] = [t.strip() for t in row.tags.split(",") if t.strip()]
        for tag in tags_list:
            tag_counter[tag] += 1
        is_stale = bool(row.is_stale)
        if is_stale:
            stale_count += 1
        if row.folder:
            folder_notes.setdefault(row.folder, []).append(
                (
                    f"[[{row.stem}]]",
                    row.title,
                    row.summary,
                    tags_list,
                    is_stale,
                )
            )
        if row.mtime >= cutoff_ts:
            recent_notes.append((row.mtime, Path(row.path), row.folder, row.summary))

    for entries in folder_notes.values():
        entries.sort(key=lambda entry: entry[0].lower())
    recent_notes.sort(key=lambda x: x[0], reverse=True)
    recent_notes = recent_notes[:RECENT_MAX]

    claude_md = build_claude_md(
        vault,
        now_str,
        total_notes=total_notes,
        stale_count=stale_count,
        tag_counter=tag_counter,
        recent_notes=recent_notes,
        folder_notes=folder_notes,
    )
    tags_md = build_tags_md(tag_counter, now_str)
    return claude_md, tags_md, folder_notes, tag_counter
