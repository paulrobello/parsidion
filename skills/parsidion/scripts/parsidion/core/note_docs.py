"""Generate CLAUDE.md / TAGS.md / MANIFEST.md from ``note_index`` rows.

Owns the three generated vault docs end to end:

- the doc-generation constants (:data:`FOLDER_ORDER`, :data:`RECENT_DAYS`,
  :data:`RECENT_MAX`, hoisted from ``cli.index._common``);
- the Markdown emitters (:func:`build_tags_md` / :func:`build_manifests`,
  hoisted verbatim from ``cli.index.render``; :func:`build_claude_md`,
  extracted verbatim from ``cli.index.build.build_index``'s inline assembly)
  — also callable with parse-derived structures, which is the
  byte-equivalence seam the docs tests exercise;
- :func:`load_note_index_rows` — read every ``note_index`` row as a
  :class:`~parsidion.core.note_index.NoteEntry` (ordered by path, the same
  order the sorted parse walk produces);
- :func:`render_docs_from_rows` — the row-driven doc generation: derive the
  tag counter, per-folder manifest entries, recent-activity list and stale
  count from the rows alone (no note parsing), then emit the same bytes the
  parse-derived structures produce.

Every field the docs render is carried by a NoteEntry row, so a no-change
incremental ``update_index`` run regenerates the docs in O(changed) without
re-parsing the vault. Caveat: ``note_index`` is stem-keyed, so when two note
files share a stem the table holds only the walk-order winner's row; docs
generated from rows reflect winner semantics while the parse path counts
every file. A test pins that divergence so it stays intentional.
"""

from __future__ import annotations

import json
import sqlite3
from collections import Counter
from datetime import datetime, timedelta
from pathlib import Path

from .frontmatter import _WIKILINK_RE, _wikilink
from .note_index import STALE_DAYS, NoteEntry
from .vault_fs import atomic_write_text
from .vault_path import get_embeddings_db_path

__all__: list[str] = [
    # Doc-generation constants (hoisted from cli.index._common)
    "FOLDER_ORDER",
    "RECENT_DAYS",
    "RECENT_MAX",
    # Markdown emitters (hoisted from cli.index.render / cli.index.build)
    "build_claude_md",
    "build_tags_md",
    "build_manifests",
    # Row-driven doc generation
    "load_note_index_rows",
    "render_docs_from_rows",
]

# Canonical folder order for index sections
FOLDER_ORDER: list[str] = [
    "Daily",
    "Projects",
    "Languages",
    "Frameworks",
    "Patterns",
    "Debugging",
    "Tools",
    "Research",
    "History",
]

# Recent-activity section: window and cap.
RECENT_DAYS: int = 7
RECENT_MAX: int = 20


def build_tags_md(tag_counter: Counter[str], now_str: str) -> str:
    """Build the TAGS.md content with the full tag cloud and tag list.

    Args:
        tag_counter: Tag frequency counter from build_index().
        now_str: Timestamp string for the header.

    Returns:
        Complete TAGS.md file content.
    """
    lines: list[str] = []
    lines.append("# Vault Tags")
    lines.append("")
    lines.append(f"> Auto-generated by update_index.py on {now_str}")
    lines.append("> Do not edit manually - changes will be overwritten")
    lines.append("")

    # Tag Cloud (human-readable, sorted by frequency)
    lines.append("## Tag Cloud")
    if tag_counter:
        tag_parts: list[str] = []
        for tag, count in tag_counter.most_common():
            tag_parts.append(f"`{tag}` ({count})")
        lines.append(" | ".join(tag_parts))
    else:
        lines.append("_No tags found._")
    lines.append("")

    # Existing Tags (machine-readable for the AI summarizer)
    lines.append("## Existing Tags")
    if tag_counter:
        lines.append(", ".join(sorted(tag_counter.keys())))
    else:
        lines.append("")
    lines.append("")

    return "\n".join(lines)


def build_manifests(
    folder_notes: dict[str, list[tuple[str, str, str, list[str], bool]]],
    vault: Path,
    now_str: str | None = None,
) -> list[Path]:
    """Generate a MANIFEST.md file inside each non-empty vault subfolder.

    Each manifest contains a Markdown table with one row per note, showing the
    note stem as a wikilink, its tags, and a one-line summary. Stale notes are
    marked with a warning emoji in the Note column.

    Args:
        folder_notes: Mapping from folder name to list of
            (wikilink, title, summary, tags, is_stale) tuples, as returned by
            ``build_index()`` or :func:`render_docs_from_rows`.
        vault: Vault root (manifests are written to ``vault/<folder>/``).
        now_str: Timestamp string for the header comment; None stamps the
            current time (the historical behaviour).

    Returns:
        A list of Path objects for all MANIFEST.md files written.
    """
    if now_str is None:
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M")
    written: list[Path] = []

    for folder_name, entries in folder_notes.items():
        if not entries:
            continue

        folder_dir: Path = vault / folder_name
        if not folder_dir.is_dir():
            continue

        note_count: int = len(entries)
        lines: list[str] = []
        lines.append(f"# {folder_name} — Vault Notes ({note_count} notes)")
        lines.append(
            f"<!-- Auto-generated by update_index.py on {now_str} — do not edit manually -->"
        )
        lines.append("")
        lines.append("| Note | Tags | Summary |")
        lines.append("|------|------|---------|")

        for wlink, _title, summary, tags, is_stale in entries:
            # wlink is like [[stem]] — extract stem for display
            stem_match = _WIKILINK_RE.match(wlink)
            stem: str = stem_match.group(1) if stem_match else wlink

            stale_prefix: str = "⚠️ " if is_stale else ""
            note_cell: str = f"{stale_prefix}[[{stem}]]"

            tags_cell: str = " ".join(f"`{t}`" for t in tags) if tags else ""
            # Escape pipe characters in summary to avoid breaking the table
            summary_cell: str = summary.replace("|", "\\|") if summary else ""

            lines.append(f"| {note_cell} | {tags_cell} | {summary_cell} |")

        lines.append("")
        content: str = "\n".join(lines)

        manifest_path: Path = folder_dir / "MANIFEST.md"
        # QA-017: route through atomic_write_text so an interrupt cannot
        # leave a half-written MANIFEST.md (the index regenerates these, but
        # a truncated file is still a confusing experience mid-rebuild).
        atomic_write_text(manifest_path, content)
        written.append(manifest_path)

    return written


